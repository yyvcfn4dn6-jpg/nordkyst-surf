/* =========================================================================
   PSM — Peniche Swell Model
   Atlantic surf is mostly GROUNDSWELL: waves generated by storms far out in
   the North Atlantic that arrive long after the wind that made them. What
   decides the surf at a Peniche beach is therefore
     1. the swell trains offshore (height, period, direction – usually 2–3 at once),
     2. how much of each train reaches the beach (swell window, refraction
        around the peninsula and Baleal, shelter behind the harbour walls),
     3. how big it breaks (shoaling: long-period swell grows much more),
     4. what the LOCAL wind does to the faces, the tide, and
     5. whether the sea is clean (one dominant long-period swell) or a mess
        (local wind-sea on top, crossing swells, storm sea).
   ========================================================================= */
(function(root){
"use strict";
const RAD = Math.PI/180, G = 9.81;
const clamp=(x,a,b)=>Math.max(a,Math.min(b,x));
const lerp=(x,x0,x1,y0,y1)=>y0+(clamp(x,x0,x1)-x0)/(x1-x0)*(y1-y0);
function angDiff(a,b){ let d=Math.abs(((a-b)%360+360)%360); return d>180?360-d:d; }

/* Komar & Gaughan breaker height (deep-water H0, period T) */
function komar(H0, T){ return 0.39*Math.pow(G,0.2)*Math.pow(Math.max(T,1)*H0*H0, 0.4); }

/* how much of a swell train from `dir` with period `T` reaches the spot (0..1)
   Long-period swell refracts (wraps) more, so the window widens with T.      */
function windowFactor(spot, dir, T){
  if(dir==null) return 0.4;
  const half = spot.swellHalf + clamp((T-8)*3, 0, 15);
  const dd = angDiff(dir, spot.bestSwell);
  if(dd < half) return 0.35 + 0.65*Math.cos(dd/half*Math.PI/2);
  if(dd < half+25) return lerp(dd, half, half+25, 0.35, 0.05);
  return 0.05;
}

/* breaking height of one component at the spot (m, roughly "set face") */
function compBreak(spot, c){
  if(!c || c.H==null || c.H<=0.02) return 0;
  const T = c.T||6;
  let hb = komar(c.H, T) * 0.75 * windowFactor(spot, c.dir, T) * spot.exposure;
  if(T < 6) hb *= lerp(T, 3, 6, 0.45, 0.8);   // short wind-sea: mostly chop, little push
  return hb;
}

/* components: [{H,T,dir,kind:"swell"|"swell2"|"wind"}] → per-spot breaking picture */
function atSpot(spot, comps, cal){
  const size = (cal && cal.size) || 1;
  let E=0, dom=null, domE=0;
  const parts = comps.map(c=>{ const hb=compBreak(spot,c); E+=hb*hb; if(hb*hb>domE){domE=hb*hb; dom=c;} return {...c, hb}; });
  const hb = Math.sqrt(E)*size;
  return {hb, dom, parts};
}

/* sea-state descriptors from the offshore components */
function seaState(comps){
  const sw = comps.filter(c=>c.kind!=="wind" && c.H!=null);
  const ww = comps.find(c=>c.kind==="wind");
  const p = sw.reduce((a,c)=>!a||c.H>a.H?c:a, null);
  const Es = sw.reduce((a,c)=>a+c.H*c.H,0), Ew = ww&&ww.H? ww.H*ww.H : 0;
  const Hs = Math.sqrt(Es+Ew);
  const windFrac = Hs>0 ? Ew/(Es+Ew) : 0;
  // crossing swells: a second train with real energy from a clearly different direction
  let cross = 0;
  if(sw.length>1 && p){ sw.forEach(c=>{ if(c===p) return; if(c.H>=0.4 && c.H>=0.45*p.H && angDiff(c.dir,p.dir)>=35) cross=Math.max(cross, c.H/p.H); }); }
  return {Hs, Tp: p?p.T:null, dir: p?p.dir:null, windH: ww?ww.H||0:0, windT: ww?ww.T:null, windFrac, cross, primary:p};
}

/* 0..1 clean-ness of the sea itself (before local wind on the faces) */
function seaClean(ss){
  let c = 1;
  c *= 1 - 0.6*clamp((ss.windFrac-0.15)/0.55, 0, 1);    // wind-sea share
  c *= 1 - 0.25*clamp(ss.cross-0.45, 0, 0.55)/0.55;       // crossing trains
  if(ss.Tp!=null) c *= lerp(ss.Tp, 6, 10, 0.75, 1);          // short period = less organised
  return clamp(c, 0.2, 1);
}

/* coast-wide classification for one hour */
function seaClass(ss, ws){
  if(ss.Hs==null) return null;
  if(ss.windH>=1.8 || (ss.windH>=1.3&&ws!=null&&ws>=10) || (ws!=null&&ws>=14) || (ss.Hs>=4&&ss.Tp!=null&&ss.Tp<10&&ss.windFrac>0.3) || ss.Hs>=6.5) return {k:"storm", t:"Stormy", c:"#b42324", d:"Storm sea: big, short-period and wind-driven. Everything is messy and dangerous – not a surf day."};
  if(ss.Hs>=3.0 || (ss.Hs>=2.3 && ss.Tp>=14)) return {k:"xl", t:"Big & powerful", c:"#7a3fbf", d:"Heavy groundswell (often 3–5 m offshore). Exposed beaches close out and rips are strong; only the sheltered corners (Molhe Leste, Cantinho da Baía) are even worth a look."};
  if(ss.windFrac>0.45 || ss.cross>0.75 || (ss.Tp!=null&&ss.Tp<7.5&&ss.Hs>1)) return {k:"mixed", t:"Mixed / lumpy", c:"#f07a2a", d:"Wind-sea and crossing swells on top of each other: waves arrive in uneven, lumpy peaks. Surfable, rarely clean."};
  if(ss.Hs<0.7) return {k:"small", t:"Small", c:"#6da7ec", d:"Little swell around – knee-high fun at the exposed beaches at best."};
  if(ss.Tp>=10 && ss.windFrac<0.25) return {k:"clean", t:"Clean groundswell", c:"#1fa463", d:"One organised long-period swell, little wind-sea – the classic Peniche setup. Pick the beach the wind is offshore at."};
  return {k:"mod", t:"Moderate", c:"#f2b01e", d:"Mid-period swell with some wind-sea. Decent at the right beach, a bit unorganised."};
}

/* tide position 0 (low) … 1 (high) from the surrounding sea-level curve */
function tideNorm(sl, i){
  if(!sl || sl[i]==null) return null;
  let lo=Infinity, hi=-Infinity;
  for(let k=Math.max(0,i-7); k<=Math.min(sl.length-1,i+7); k++){ const v=sl[k]; if(v==null) continue; if(v<lo) lo=v; if(v>hi) hi=v; }
  if(!(hi-lo>0.15)) return 0.5;
  return (sl[i]-lo)/(hi-lo);
}
function tideTrend(sl, i){ const a=sl[i-1], b=sl[i+1]; if(a==null||b==null) return 0; return b-a; }
/* high/low water times (unix) from hourly sea level, parabolic refinement */
function tideTurns(times, sl){
  const out=[];
  for(let i=1;i<sl.length-1;i++){ const a=sl[i-1], b=sl[i], c=sl[i+1]; if(a==null||b==null||c==null) continue;
    const isHi=b>=a&&b>c, isLo=b<=a&&b<c; if(!isHi&&!isLo) continue;
    const den=a-2*b+c, off=den!==0?clamp(0.5*(a-c)/den,-0.5,0.5):0;
    out.push({t:times[i]+off*3600, h:b-0.25*(a-c)*off, hi:isHi}); }
  return out;
}
const TIDE_PREF = {"low":0.15, "low-mid":0.35, "mid":0.5, "mid-high":0.65, "high":0.85};
function tideScore(spot, x){
  if(x==null || spot.tide==="all") return 1;
  const c = TIDE_PREF[spot.tide]??0.5;
  return 1 - 0.32*clamp((Math.abs(x-c)-0.22)/0.4, 0, 1);
}
const tideWord = x => x==null?"–":x<0.25?"low":x<0.45?"low–mid":x<0.6?"mid":x<0.8?"mid–high":"high";

/* ---------------- quality for a surfer with a comfort ceiling ---------------- */
function windRel(spot, wd){ return angDiff(wd, spot.facing); }   // 0 onshore, 180 offshore
function windLabel(rel, ws){ if(ws<2.5) return "glassy"; return rel>=135?"offshore":rel>=100?"side-off":rel>=70?"cross-shore":rel>=40?"cross-on":"onshore"; }
function windScore(rel, ws){
  if(ws<2.5) return 1;
  if(rel>=135) return ws<9?1:ws<13?0.8:0.5;           // strong offshore = hard to paddle in, spray
  if(rel>=100) return ws<7?0.95:ws<10?0.8:ws<13?0.55:0.35;
  if(rel>=70)  return ws<5?0.8:ws<8?0.55:ws<11?0.35:0.2;
  if(rel>=40)  return ws<4?0.7:ws<6?0.45:ws<9?0.28:0.12;
  return ws<3.5?0.65:ws<5.5?0.38:ws<8?0.22:0.08;      // Atlantic onshore blows it out fast
}
/* size: rises to the spot minimum, full marks up to the comfort max, then drops hard */
function sizeScore(hb, min, M){
  if(hb==null || hb<min*0.7) return 0;
  if(hb<min) return lerp(hb, min*0.7, min, 0, 0.35);
  const full = Math.max(min*1.15, 0.7*M);
  if(hb<full) return lerp(hb, min, full, 0.35, 1);
  if(hb<=M) return 1;
  if(hb<1.3*M) return lerp(hb, M, 1.3*M, 1, 0.3);
  if(hb<1.7*M) return lerp(hb, 1.3*M, 1.7*M, 0.3, 0.05);
  return 0.03;
}
function periodScore(T){ if(T==null) return 0.6; return T<6?0.3:T<8?lerp(T,6,8,0.3,0.7):T<11?lerp(T,8,11,0.7,1):1; }

/* full evaluation of one hour at one spot */
function evaluate(spot, comps, wind, tideX, M, cal){
  if(!comps || !comps.length || wind==null || wind.ws==null) return {q:null};
  const ss = seaState(comps), sp = atSpot(spot, comps, cal);
  const rel = windRel(spot, wind.wd), wsc = windScore(rel, wind.ws), sc = seaClean(ss);
  const sz = sizeScore(sp.hb, spot.minWave, M), ts = tideScore(spot, tideX);
  const T = sp.dom ? sp.dom.T : ss.Tp;
  let q = sz * (0.25+0.75*wsc) * (0.5+0.5*periodScore(T)) * (0.45+0.55*sc) * ts;
  const cls = seaClass(ss, wind.ws);
  if(cls && cls.k==="storm") q *= 0.5;                        // storm sea: unsafe/unpleasant even where it's small
  if(cal && cal.qBias && q>0.05) q = clamp(q+cal.qBias, 0, 1);
  // surface: how clean the faces will feel (0..1) – wind on the faces × the sea itself
  const clean = clamp(wsc*0.65 + sc*0.35, 0, 1);
  const tooBig = sp.hb > M*1.15, hold = sp.hb > spot.maxHold;
  return {q, hb:sp.hb, T, dir: sp.dom?sp.dom.dir:ss.dir, rel, ws:wind.ws, wd:wind.wd, clean, cleanW: cleanWord(clean), tooBig, hold, ss, parts: sp.parts, sz, wsc, sc, ts};
}
const cleanWord = c => c>=0.85?"Clean":c>=0.68?"Semi-clean":c>=0.48?"Bumpy":c>=0.3?"Choppy":"Blown out";

root.PSM = {komar, windowFactor, compBreak, atSpot, seaState, seaClean, seaClass, tideNorm, tideTrend, tideTurns, tideScore, tideWord,
  windRel, windLabel, windScore, sizeScore, periodScore, evaluate, cleanWord, angDiff};
})(typeof window!=="undefined"?window:globalThis);
